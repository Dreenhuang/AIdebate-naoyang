// 根据ID获取特定soul预设
export function getSoulPresetById(roleType, presetId) {
  const presets = soulPresets[roleType] || [];
  return presets.find(p => p.id === presetId);
}

// 随机获取一个soul预设
export function getRandomSoulPreset(roleType) {
  const presets = soulPresets[roleType] || [];
  if (presets.length === 0) return null;
  return presets[Math.floor(Math.random() * presets.length)];
}

// 根据难度筛选soul预设
export function getSoulPresetsByDifficulty(roleType, difficulty) {
  const presets = soulPresets[roleType] || [];
  return presets.filter(p => p.difficulty === difficulty);
}

